export type TaskPlan = {
  make: string;
  steps: string[];
  notes: string[];
  method: InstallMethod;
};

/** Шаги русификации для марки: от самого простого к сложному. */
export function russificationPlan(make: string): TaskPlan {
  const method = installMethodFor(make);
  return {
    make,
    method,
    steps: [
      "Откройте на магнитоле «Настройки → Язык» и посмотрите список. Если есть «Русский», выберите его: на этом всё.",
      "Если русского нет, проверьте обновление системы: оно часто добавляет язык для вашего рынка. " + method.headline + ".",
      "Спросите у дилера или в поддержке марки, какая версия системы у вас стоит и есть ли в ней русский.",
      "Если магнитола на Android и в её меню есть «Для разработчиков» или «Отладка по Wi‑Fi»: подключитесь по Wi‑Fi, приложение откроет выбор языка на экране магнитолы.",
      "Для карт и голоса поставьте Яндекс Навигатор или 2ГИС (из RuStore): они говорят по-русски независимо от языка системы.",
    ],
    notes: [
      "Язык меню, голос и карты это три разные вещи: язык системы можно сменить, а навигация работает как отдельная программа.",
      ...method.limits,
    ],
  };
}

